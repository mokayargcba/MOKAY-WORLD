// Regenerates web/npc-data.js and web/sprites/ NPC images from the Android app.
// Run: node web-tools/extract-npcs.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dataDir = `${root}/app/src/main/java/com/example/game/data`;
const drawableDir = `${root}/app/src/main/res/drawable`;
const files = ['MokayRegionsTier1.kt', 'MokayRegionsTier2.kt', 'MokayRegionsTier3.kt', 'MokayWorldCatalog.kt'];
const TARGET_W = 1800;
const TARGET_H = 1200;

const str = (block, key) => {
  const m = block.match(new RegExp(`\\b${key}\\s*=\\s*"((?:[^"\\\\]|\\\\.)*)"`));
  return m ? m[1].replace(/\\"/g, '"').replace(/\\\$/g, '$') : undefined;
};
const num = (block, key) => {
  const m = block.match(new RegExp(`\\b${key}\\s*=\\s*(-?[0-9.]+)f?`));
  return m ? parseFloat(m[1]) : undefined;
};
const enumVal = (block, key, type) => {
  const m = block.match(new RegExp(`\\b${key}\\s*=\\s*${type}\\.([A-Z_]+)`));
  return m ? m[1] : undefined;
};

function parenBlock(src, openIdx) {
  let depth = 0;
  let inStr = false;
  for (let i = openIdx; i < src.length; i++) {
    const c = src[i];
    if (inStr) {
      if (c === '\\') i++;
      else if (c === '"') inStr = false;
      continue;
    }
    if (c === '"') inStr = true;
    else if (c === '(') depth++;
    else if (c === ')') {
      depth--;
      if (depth === 0) return src.slice(openIdx, i + 1);
    }
  }
  return src.slice(openIdx);
}

const regionSizes = {};
const npcs = [];
for (const f of files) {
  const src = fs.readFileSync(`${dataDir}/${f}`, 'utf8');
  for (const m of src.matchAll(/RegionSpec\(/g)) {
    const head = src.slice(m.index, m.index + 800);
    const id = enumVal(head, 'id', 'RegionId');
    const w = num(head, 'worldWidth');
    const h = num(head, 'worldHeight');
    if (id && w && h && !regionSizes[id]) regionSizes[id] = { w, h };
  }
  for (const m of src.matchAll(/NpcSpec\(/g)) {
    const b = parenBlock(src, m.index + 'NpcSpec'.length);
    const id = str(b, 'id');
    if (!id) continue;
    npcs.push({
      id,
      name: str(b, 'name'),
      role: str(b, 'role'),
      visual: enumVal(b, 'visual', 'CharacterVisual'),
      region: enumVal(b, 'regionId', 'RegionId'),
      x: num(b, 'x'),
      y: num(b, 'y'),
      dialogue: str(b, 'dialogue'),
      questId: str(b, 'questId'),
      village: str(b, 'villageName') || '',
      shop: /offersShop\s*=\s*true/.test(b)
    });
  }
}

const spriteFile = (v) => {
  if (v.startsWith('CITIZEN_')) return `sprite_cit_${v.slice(8).toLowerCase()}.png`;
  if (v === 'LA_LLAVE') return 'sprite_npc_llave.png';
  return `sprite_npc_${v.toLowerCase()}.png`;
};

const byRegion = {};
const seen = new Set();
for (const n of npcs) {
  if (seen.has(n.id)) continue;
  seen.add(n.id);
  const size = regionSizes[n.region];
  if (!size) {
    console.error('missing region size for', n.region, n.id);
    continue;
  }
  const sprite = spriteFile(n.visual);
  fs.mkdirSync(`${root}/web/sprites`, { recursive: true });
  if (fs.existsSync(`${drawableDir}/${sprite}`)) {
    fs.copyFileSync(`${drawableDir}/${sprite}`, `${root}/web/sprites/${sprite}`);
  } else {
    console.error('missing sprite', sprite);
  }
  const rid = n.region.toLowerCase();
  (byRegion[rid] ||= []).push({
    id: n.id,
    name: n.name,
    role: n.role,
    village: n.village,
    x: Math.round((n.x * TARGET_W) / size.w),
    y: Math.round((n.y * TARGET_H) / size.h),
    shop: n.shop,
    ...(n.questId ? { questId: n.questId } : {}),
    visual: n.visual,
    sprite: `sprites/${sprite}`,
    dialogue: n.dialogue
  });
}

const dialogues = JSON.parse(fs.readFileSync(`${root}/app/src/main/assets/npc_dialogues.json`, 'utf8')).trees;
const out =
  '// Generated by web-tools/extract-npcs.mjs from the Android app. Do not edit by hand.\n' +
  `window.MOKAY_APP_NPCS = ${JSON.stringify(byRegion, null, 1)};\n` +
  `window.MOKAY_APP_DIALOGUES = ${JSON.stringify(dialogues)};\n`;
fs.writeFileSync(`${root}/web/npc-data.js`, out);

console.log('regions', Object.keys(regionSizes).length, 'npcs', seen.size, 'dialogue trees', Object.keys(dialogues).length);
for (const [r, list] of Object.entries(byRegion)) {
  console.log(r, list.map((n) => `${n.id}(${n.x},${n.y})${dialogues[n.id] ? '*' : ''}`).join(' '));
}
